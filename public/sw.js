// Service worker mínimo: permite instalar la app y abrir la pantalla aunque se caiga la red.
// Red primero (siempre la versión nueva); si no hay red, usa lo último guardado.
// Nunca guarda llamadas a Supabase: ventas y datos siempre van directo a la base.
const CACHE = 'pancho-v1';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(
  caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())
));

self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(
    fetch(req).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req).then(r => r || caches.match('/')))
  );
});
